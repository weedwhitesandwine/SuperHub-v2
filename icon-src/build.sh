#!/bin/bash
# Build SuperHub-v2's button pictures from the Lucide icons in icon-src/lucide
# (Lucide 0.460.0, ISC licence, stroke thinned to 1.5) and write src/icons.ts.
#   bash icon-src/build.sh            (from the plugin folder)
# map.txt says which Lucide icon each SuperHub name came from.
set -e
cd "$(dirname "$0")/.."
rm -f assets/hub/icons/*.png
for f in icon-src/lucide/[!_]*.svg; do
  n=$(basename "$f" .svg)
  rsvg-convert -w 160 -h 160 "$f" -o "assets/hub/icons/$n.png" &
done
wait
{
  echo '// Generated by icon-src/build.sh: every picture a home button can use (Lucide, ISC).'
  echo 'export const ICONS: Record<string, any> = {'
  for f in assets/hub/icons/*.png; do n=$(basename "$f" .png); echo "  '$n': require('../assets/hub/icons/$n.png'),"; done
  echo '};'
} > src/icons.ts
ls assets/hub/icons | wc -l
